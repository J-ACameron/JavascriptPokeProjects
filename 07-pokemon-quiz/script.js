const displayQuestion = document.getElementById("currentQuestion")
const displayOptions = document.getElementById("answerBox")
const displayScore = document.getElementById("score")
const screens = document.querySelectorAll(".screen");
const confirmBtn = document.getElementById("difficultyBtn")
const retryBtn = document.getElementById("retryBtn")
const reviewBox = document.getElementById('reviewBox')
const countdown = document.getElementById('countdown')



let state = {
    userDifficulty: null,
    score: 0,
    currentIndex: 0,
    userAnswer:[],
    clock: 15,
    timerId: null
};

function showScreen(id){
    screens.forEach(s => s.classList.add("hidden"));
    document.getElementById(id).classList.remove("hidden")
}

function startQuiz(){
    state.userDifficulty = document.getElementById("difficulty").value
    showScreen("questionScreen")
    renderQuestion(state.currentIndex)
    reviewBox.innerHTML = ""
}

function startTimer() {
    clearInterval(state.timerId);
    state.clock = 15;
    countdown.textContent = state.clock;

    state.timerId = setInterval(() => {
        state.clock--;
        countdown.textContent = state.clock;
        if (state.clock <= 0) {
            clearInterval(state.timerId);
            nextQuestion();
        }    }, 1000);
}

function renderQuestion(index){
    const questionUserDif = questionList[state.userDifficulty]
    const currentSet = questionUserDif[index]
    const currentDisplay = currentSet.question
    const currentOptions = currentSet.options
    displayQuestion.textContent = currentDisplay
    displayOptions.innerHTML = ""
    startTimer()
    currentOptions.forEach(option => {
        const optionBtn = document.createElement("button");
        optionBtn.textContent = option;
        optionBtn.addEventListener('click', () =>{ 
            state.userAnswer.push(option) 
            if(option === currentSet.correct){
                state.score++
                displayScore.textContent = state.score
            }
            nextQuestion()
        })  
            displayOptions.appendChild(optionBtn)
            
    })
}

function nextQuestion(){
    state.currentIndex++
    const pool = questionList[state.userDifficulty];
    if(state.currentIndex >= questionList[state.userDifficulty].length){
        const finalScore = document.getElementById("result")
        finalScore.textContent = `Final Score: ${state.score}`
        pool.forEach((question, i) => {
            const row = document.createElement("p")
            row.textContent = `Question:${question.question},
            Your Answer: ${state.userAnswer[i]}, 
            Question Answer: ${question.correct}`

            reviewBox.appendChild(row)
        })
        showScreen("resultScreen")
    }else{
        renderQuestion(state.currentIndex)
    }
}

function resetGame(){
    state = {
        userDifficulty: null,
        score: 0,
        currentIndex: 0,
        userAnswer:[]
    };
    showScreen("difficultyScreen")
}

confirmBtn.addEventListener('click', startQuiz)
retryBtn.addEventListener('click', resetGame)

